// GitHub Pages can serve the source tree directly. Keep its installed worker's recovery
// bytes in sync with dist, even when WebKit exposes an empty CacheStorage after restart.
import {createHash} from 'node:crypto';
import {readFile,readdir,writeFile} from 'node:fs/promises';
import {extname} from 'node:path';
import {gzipSync} from 'node:zlib';

const sourceMime={'.html':'text/html;charset=utf-8','.js':'text/javascript','.css':'text/css','.jpg':'image/jpeg','.webp':'image/webp','.svg':'image/svg+xml'};
const mime={...sourceMime,'.png':'image/png','.webmanifest':'application/manifest+json'};
// Bundle only compact battle icons; 800px source artwork remains in the repository.\nconst icons=(await readdir('assets/icons',{recursive:true})).filter(name=>extname(name)==='.png' && (!name.includes('/') || (name.startsWith('damage/') && name.endsWith('_64.png')))).sort();
const paths=['index.html','rpg-visual-types.js','site.webmanifest',...icons.map(name=>'assets/icons/'+name),'companion-result-card.js','companion-result-card.css','vfx-gallery.html',...(await readdir('src',{recursive:true})).filter(p=>sourceMime[extname(p)]).map(p=>'src/'+p).sort()];
const digest=createHash('sha256'),assets={};
for(const path of paths){
 const bytes=await readFile(path),type=mime[extname(path)],compressed=type.startsWith('text/')||type==='application/manifest+json';
 digest.update(path+'\0').update(bytes);
 assets[path]=[type,compressed,(compressed?gzipSync(bytes):bytes).toString('base64')];
}
const revision=digest.digest('hex').slice(0,16);
const output='// Generated by npm run offline:sync. Static app assets only.\nself.KobeShellRevision='+JSON.stringify(revision)+';\nself.KobeShellAssets='+JSON.stringify(assets)+';\n';
if(process.argv.includes('--write'))await writeFile('offline-shell.js',output);
else if(!(await readFile('offline-shell.js','utf8')).startsWith(output.split('\n').slice(0,2).join('\n')+'\n'))throw Error('Ressources modifiées : exécutez npm run offline:sync avant le build.');
